const dictionaries: Record<Language, Dictionary> = { en, ar }

function readInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'en'
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored === 'ar' || stored === 'en') return stored
  } catch {
    /* ignore storage errors */
  }
  return 'en'
}

function applyDocumentLanguage(language: Language): void {
  if (typeof document === 'undefined') return
  document.documentElement.lang = language
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
}

interface LocaleState {
  language: Language
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
}

export const useLocaleStore = create<LocaleState>()((set, get) => ({
  language: readInitialLanguage(),
  setLanguage: (language) => {
    try {
      window.localStorage.setItem(STORAGE_KEY, language)
    } catch {
      /* ignore storage errors */
    }
    applyDocumentLanguage(language)
    set({ language })
  },
  toggleLanguage: () => {
    get().setLanguage(get().language === 'en' ? 'ar' : 'en')
  }
}))

applyDocumentLanguage(useLocaleStore.getState().language)

export function getLanguage(): Language {
  return useLocaleStore.getState().language
}

export function translate(language: Language, key: string, variables?: Record<string, string | number>): string {
  let value = dictionaries[language][key] ?? en[key] ?? key
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return value
}

export function t(key: string, variables?: Record<string, string | number>): string {
  return translate(getLanguage(), key, variables)
}

export function useTranslation(): {
  t: (key: string, variables?: Record<string, string | number>) => string
  language: Language
  isRtl: boolean
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
} {
  const language = useLocaleStore((state) => state.language)
  const setLanguage = useLocaleStore((state) => state.setLanguage)
  const toggleLanguage = useLocaleStore((state) => state.toggleLanguage)
  return {
    t: (key, variables) => translate(language, key, variables),
    language,
    isRtl: language === 'ar',
    setLanguage,
    toggleLanguage
  }
}
